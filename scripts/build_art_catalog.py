"""Writes static/js/artCatalog.js: every vendored ASCII Magic piece's slug, name and category,
so the Appearance panel can list and search them without loading 732 modules.

Run after updating static/vendor/ascii-magic:  python scripts/build_art_catalog.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / "static" / "vendor" / "ascii-magic"
TARGET = ROOT / "static" / "js" / "artCatalog.js"
# Each piece declares its meta in one of two styles: `slug: "x"` or `"slug": "x"`.
FIELD = r'"?{0}"?\s*:\s*"([^"]*)"'


def field(source, name):
    match = re.search(FIELD.format(name), source)
    if not match:
        raise ValueError(f"no {name}")
    return match.group(1)


def catalog():
    categories = [(c["id"], c["name"]) for c in json.loads((VENDOR / "categories.json").read_text(encoding="utf-8"))]
    order = {cid: i for i, (cid, _) in enumerate(categories)}
    pieces = []
    for path in sorted((VENDOR / "pieces").glob("*.js")):
        meta = path.read_text(encoding="utf-8").split("export const meta", 1)[1]
        slug, name, category = field(meta, "slug"), field(meta, "name"), field(meta, "category")
        if slug != path.stem:
            raise ValueError(f"{path.name} declares slug {slug}")
        if category not in order:
            raise ValueError(f"{path.name} has unknown category {category}")
        pieces.append((slug, name, category))
    pieces.sort(key=lambda p: (order[p[2]], p[1].lower()))
    used = {p[2] for p in pieces}
    return [c for c in categories if c[0] in used], pieces


def render(categories, pieces):
    rows = ",\n".join("  " + json.dumps(list(p)) for p in pieces)
    return ("// Generated by scripts/build_art_catalog.py from static/vendor/ascii-magic. Do not edit.\n"
            f"export const ART_CATEGORIES = Object.freeze({json.dumps([list(c) for c in categories])});\n"
            f"export const ART_CATALOG = Object.freeze([\n{rows},\n]);\n")


if __name__ == "__main__":
    categories, pieces = catalog()
    TARGET.write_text(render(categories, pieces), encoding="utf-8", newline="\n")
    print(f"{TARGET.relative_to(ROOT)}: {len(pieces)} pieces in {len(categories)} categories")
